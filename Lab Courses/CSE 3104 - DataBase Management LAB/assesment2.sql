BONUS_AMMOUNT INT,
FOREIGN KEY (WORKER_ID_REF) REFERENCES WORKER(WORKER_ID)
);

create TABLE TITLE(
WORKER_ID_REF INT,
WORKER_TITLE VARCHAR(50),
AFFECTED_FROM DATE,
FOREIGN KEY (WORKER_ID_REF) REFERENCES WORKER(WORKER_ID)

