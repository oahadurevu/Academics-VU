select FIRST_NAME +' ' +LAST_NAME AS FULL_NAME FROM WORKER WHERE DEPT_NAME='IT';

select FIRST_NAME +' ' +LAST_NAME  AS FULL_NAME , SALARY  FROM WORKER WHERE  SALARY >10000;

SELECT UPPER(FIRST_NAME) AS NAME FROM WORKER;
SELECT LOWER(FIRST_NAME) AS NAME FROM WORKER;

SELECT FIRST_NAME, LEN(FIRST_NAME) AS LENGTH FROM WORKER;

SELECT *
FROM WORKER
WHERE FIRST_NAME LIKE 'A%';

SELECT LEFT(FIRST_NAME,3)
FROM WORKER;

SELECT RIGHT(LAST_NAME,2)
FROM WORKER;


SELECT FIRST_NAME, REPLACE(DEPT_NAME,'IT','TECH') AS DEPT
FROM WORKER;

SELECT TOP 5 FIRST_NAME + SPACE(10) + LAST_NAME AS FULL_NAME
FROM WORKER;

SELECT *FROM WORKER WHERE FIRST_NAME LIKE '%a%';

SELECT FIRST_NAME, REPLICATE(FIRST_NAME,2)
FROM WORKER;
SELECT FIRST_NAME, SUBSTRING(FIRST_NAME,2,3)
FROM WORKER;
SELECT *
FROM WORKER
WHERE SALARY BETWEEN 10000 AND 15000;

SELECT TOP 3 *
FROM WORKER
ORDER BY JOINING_DATE ASC;

SELECT DEPT_NAME, COUNT(*) AS TOTAL
FROM WORKER
GROUP BY DEPT_NAME;

SELECT *
FROM WORKER
WHERE SALARY = (SELECT MAX(SALARY) FROM WORKER);

SELECT DEPT_NAME, AVG(SALARY) AS AVG_SALARY
FROM WORKER
GROUP BY DEPT_NAME;

SELECT FIRST_NAME
FROM WORKER
WHERE FIRST_NAME = REVERSE(FIRST_NAME);

SELECT 
