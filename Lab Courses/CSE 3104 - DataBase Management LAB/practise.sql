  CREATE TABLE WORKER
(
    WORKER_ID INT NOT NULL,
    FIRST_NAME VARCHAR(30) UNIQUE,
    LAST_NAME VARCHAR(15),

    SALARY INT CHECK (SALARY > 100),
    DEPT_NAME VARCHAR(15),
    JOINING_DATE DATETIME,

    CONSTRAINT PK_WORKER PRIMARY KEY (WORKER_ID)
);
